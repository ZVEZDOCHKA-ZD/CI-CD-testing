import numpy as np
import matplotlib.pyplot as plt
import random as rm
import math as m



#Равномерное распределение методом "лото"
N = 100     #Выборка из 100 элементов
data = [ i/N for i in range (N)]    #Создание массива на 100 элементов от 0 до 1
print(data)
datagraph = [i/N for i in range (N)]   #Создание массива на 100 элементов для вывода на график
datanew = []    #Массив для выбранных элементов

#Метод лото
for i in range (N): 
    x = rm.random()     #Выбирается число от 0 до 1 
    y = 1   #Переменная для хранения выбранного числа
    i1 = 0  #Номер выбранного элемента
    sizedata = len(data)    #переменная размера массива данных. Обновляется при каждом удалении элемента
    for k in range (sizedata):  #Метод "лото"
        if y >= abs(x - data[k]):   #Сравнение элемента с рандомным. Если близок, то номер элемента берется. Методом перебора каждого элемента находится ближайший
            i1 = k     #Номер элемента присваивается переменной
    datanew.append(data[i1])    #Элемент "выбирается"
    del data[i1]    #И после удаляется

#Построение графика равномерно распределеного случайного процесса
plt.figure(1)
plt.plot(datagraph)
plt.title('Равномерно распределенный случайный процесс')
plt.xlabel('t')
plt.ylabel('x(t)')

#Построение гистограммы равномерно распределеного случайного процесса
plt.figure(2)
plt.hist(datanew, bins = 10, edgecolor='black')
plt.title('Гистограма равномерного распределения')
plt.xlabel('Значения')
plt.ylabel('Частота')
plt.show()

#Выделение амплитудно-частотного спектра методом Фурье
datafft = np.fft.fft(datagraph) #Использование метода
ampl = np.abs(datafft)  #Выделение амплитуд
frq = np.fft.fftfreq(len(datagraph))    #Выделение частот

#Построение амплитудно-частотного спектра
plt.figure(3)
plt.stem(frq[1:len(frq)//2], ampl[1:len(ampl)//2],  basefmt=" ") 
plt.title("Амплитудный спектр") 
plt.xlabel("Частота") 
plt.ylabel("Амплитуда") 
plt.grid(True, alpha=0.3) 
plt.tight_layout() 
plt.show()




#Распределение случайных чисел с одинаковым амплитудным спектром

N = 100     #Количество элементов
A = 1/N     #Амплитуда. Всегда постоянна

freqEqAmp = np.fft.fftfreq(N)   #Выделение частот
amplEqAmp = np.ones(N) * A      #Выделение амплитуд. Они все одинаковы и равны 1/N

FiEqAmp = np.random.uniform(0, 2*np.pi, N)  #Генерация псевдослучайных фаз

#Формирование ПСЕВДОслучайного процесса с одинаковыми амплитудами
spectr = amplEqAmp*np.exp(1j * FiEqAmp) #Формирование комплексной части спектра

#Создание симметричности спектра
for k in range(1, N//2):
    spectr[-k] = np.conj(spectr[k])

# Выделяем только вещественные значения из спектра 
spectr[0] = A 
if N % 2 == 0: 
    spectr[N//2] = A 

#Получение сигнала при помощи обратного преобразования Фурье
signal = np.real(np.fft.ifft(spectr))

#Построение графика ПСЕВДОслучайного процесса с одинаковым амплитудным спектром
plt.figure(4)
plt.plot(signal)
plt.title('ПСЕВДОслучайный процесс с одинаковым амплитудным спектром')
plt.xlabel('t')
plt.ylabel('x(t)')

#Построение гистограммы ПСЕВДОслучайного процесса с одинаковым амплитудным спектром
plt.figure(5)
plt.hist(signal, bins = 10, edgecolor='black')
plt.title('Гистограма  ПСЕВДОслучайного процесса с одинаковым амплитудным спектром')
plt.xlabel('Значения')
plt.ylabel('Частота')
plt.show()

#Построение амплитудно-частотного спектра
plt.figure(6)
plt.stem(freqEqAmp[1:len(frq)//2], amplEqAmp[1:len(ampl)//2],  basefmt=" ") 
plt.title("Амплитудный спектр") 
plt.xlabel("Частота") 
plt.ylabel("Амплитуда") 
plt.grid(True, alpha=0.3) 
plt.tight_layout() 
plt.show()




#Нормальное распределение по Боксу-Мюллера
FiB = []    #Массив рандомных значений фазы
R = []      #Массив рандомных значений R
N = 100     #Выборка из 101 элемента

for i in range(0, N):   #Присваивание рандомных значений R и фазе
    fiB = rm.random()
    r = rm.random()
    FiB.append(fiB)
    R.append(r)
    
dataBM = []     #Массив значений нормально распредленного ПСЕВДОслучайного процесса
numb = [a for a in range (0, N)]    #Создание массива значений для распределения
for i in range(0, 100):     #Использование метода Бокса-Мюллера
    dataBM.append(m.sin(2*3.14*FiB[i])*m.sqrt(-2*m.log(R[i], m.e)))

#Построение графика нормально распределеного ПСЕВДОслучайного процесса
plt.figure(7)   
plt.plot(numb , dataBM)
plt.title('Нормальное распределение по Боксу-Мюллеру ПСЕВДОслучайного процесса')
plt.xlabel('t')
plt.ylabel('x(t)')

#Построение гистограмы нормально распределеного ПСЕВДОслучайного процесса
plt.figure(8)
plt.hist(dataBM, bins = 10, edgecolor='black')
plt.title('Гистограма нормального распределения по Боксу-Мюллеру')
plt.xlabel('Значения')
plt.ylabel('Частота')
plt.show()

#Использование метода Фурье для выделение амплитудно-частотного спектра для нормально распределеного ПСЕВДОслучайного процесса
dataBMfft = np.fft.fft(dataBM)  #Использование метода
amplBM = np.abs(dataBMfft)  #Выделение амплитуд
frqBM = np.fft.fftfreq(N, d = 1)    #Выделение частот

#Построение амплитудно-частотного спектра
plt.figure(9)
plt.stem(frqBM[:N//2], amplBM[:N//2],  basefmt=" ") 
plt.title("Амплитудный спектр") 
plt.xlabel("Частота") 
plt.ylabel("Амплитуда") 
plt.grid(True, alpha=0.3) 
plt.tight_layout() 
plt.show()




